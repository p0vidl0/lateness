package envrender

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

var placeholder = regexp.MustCompile(`\$\{([A-Za-z_][A-Za-z0-9_]*)\}`)

// Expand replaces ${VAR} placeholders using lookup, up to 8 passes.
func Expand(text string, lookup func(string) (string, bool)) (string, error) {
	prev := "\x00"
	converged := false
	for range 8 {
		next := placeholder.ReplaceAllStringFunc(text, func(match string) string {
			key := placeholder.FindStringSubmatch(match)[1]
			val, ok := lookup(key)
			if !ok {
				return match
			}
			return val
		})
		if next == prev {
			text = next
			converged = true
			break
		}
		prev, text = next, next
	}
	if !converged {
		return "", fmt.Errorf("placeholder expansion did not converge")
	}
	if m := placeholder.FindAllString(text, -1); len(m) > 0 {
		uniq := make(map[string]struct{})
		for _, x := range m {
			uniq[x] = struct{}{}
		}
		keys := make([]string, 0, len(uniq))
		for k := range uniq {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		return "", fmt.Errorf("unresolved placeholders: %s", strings.Join(keys, ", "))
	}
	return text, nil
}

// WriteGenerated renders templatePath into outPath using os.Getenv for placeholders.
func WriteGenerated(templatePath, outPath, composeProjectName string) error {
	raw, err := os.ReadFile(templatePath)
	if err != nil {
		return err
	}
	text, err := Expand(string(raw), func(key string) (string, bool) {
		val, ok := os.LookupEnv(key)
		return val, ok
	})
	if err != nil {
		return err
	}
	body := strings.TrimLeft(text, " \t\r\n")
	if strings.HasPrefix(body, "#") {
		lines := strings.Split(body, "\n")
		start := 0
		for start < len(lines) && (strings.HasPrefix(lines[start], "#") || strings.TrimSpace(lines[start]) == "") {
			start++
		}
		body = strings.Join(lines[start:], "\n")
		if body != "" && !strings.HasSuffix(body, "\n") {
			body += "\n"
		}
	}
	header := fmt.Sprintf("# Generated by make render-env — do not edit.\n# Profile: .docker/env/profiles/%s.env\n\n", composeProjectName)
	out := header + body
	if !strings.HasSuffix(out, "\n") {
		out += "\n"
	}
	if err := os.WriteFile(outPath, []byte(out), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", outPath)
	return nil
}
